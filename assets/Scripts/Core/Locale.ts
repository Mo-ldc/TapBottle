const RICH_TAG = /<\/?[a-zA-Z]+(=[^>]*)?>/g;

/** 取文案（并剥离富文本标签——Cocos 的 Label 不解析 <color> 之类标签） */
export function t(key: string, lang: Lang): string {
    const e = L[key];
    if (!e) { return key; }
    const raw = lang === 'zh' ? e.zh : e.en;
    return raw.replace(RICH_TAG, '');
}
